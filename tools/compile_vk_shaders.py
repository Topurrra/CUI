#!/usr/bin/env python3
"""Regenerates the SPIR-V embedded in the Vulkan renderer.

Inputs:
    src/render/cui_render_vulkan.vert, src/render/cui_render_vulkan.frag

Output:
    src/render/generated/cui_render_vulkan_spirv.h   (cui__vk_vs and cui__vk_fs)

Run it after changing either shader:
    python3 tools/compile_vk_shaders.py

Requires: glslangValidator, on the PATH or named by --glslang or $GLSLANG.
"""
import argparse
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RENDER = os.path.join(ROOT, "src", "render")
OUT = os.path.join(RENDER, "generated", "cui_render_vulkan_spirv.h")
SHADERS = [("cui__vk_vs", "cui_render_vulkan.vert"), ("cui__vk_fs", "cui_render_vulkan.frag")]


def compile_shader(glslang, name, source, tmp):
    """One shader as the lines of a C array named `name`."""
    header = os.path.join(tmp, name + ".h")
    subprocess.run([glslang, "-V", "--quiet", "--vn", name, "-o", header, os.path.join(RENDER, source)], check=True)
    lines = []
    with open(header, encoding="utf-8") as f:
        for line in f.read().splitlines():
            if line.lstrip().startswith("//") or "pragma once" in line:
                continue
            if line.startswith("const uint32_t"):
                line = "static " + line
            lines.append(line)
    return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--glslang", default=os.environ.get("GLSLANG", "glslangValidator"), help="the glslangValidator to use")
    args = ap.parse_args()
    if not shutil.which(args.glslang):
        sys.exit("no glslangValidator (pass --glslang or set GLSLANG)")

    lines = ["/* Generated by tools/compile_vk_shaders.py from cui_render_vulkan.vert and cui_render_vulkan.frag. Do not edit. */"]
    with tempfile.TemporaryDirectory() as tmp:
        for name, source in SHADERS:
            lines += compile_shader(args.glslang, name, source, tmp)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote " + os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
