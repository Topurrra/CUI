"""Generate the terminal screen's character table (src/cui_vt_width.h) and its test data (tests/test_vt_width_data.h)
from Unicode 17.0.0.

Usage: py tools/gen_vt_width.py UCD_DIRECTORY
Inputs (from https://www.unicode.org/Public/17.0.0/, flat in one folder or in their ucd/ subfolders):
EastAsianWidth.txt, DerivedCoreProperties.txt (InCB), auxiliary/GraphemeBreakProperty.txt,
auxiliary/GraphemeBreakTest.txt, emoji/emoji-data.txt, emoji/emoji-variation-sequences.txt, emoji/emoji-test.txt,
UnicodeData.txt and DerivedNormalizationProps.txt (the compositions).
No downloaded data is needed to build CUI: both outputs are checked in.

The table is one sorted list of 32-bit words, (first code point << 11) | properties, each run lasting until the next
word. The properties (CUI__VTW_* in cui_vt_width.c):
    bits 0-1   cells: 1, or 2 for East Asian Width W or F, Emoji_Presentation, and Extended_Pictographic code points
               that are not assigned yet (future emoji)
    bits 2-5   Grapheme_Cluster_Break: Other CR LF Control Extend ZWJ Regional_Indicator Prepend SpacingMark L V T LV LVT
    bit 6      Extended_Pictographic
    bit 7      has an emoji style variation sequence (FE0F makes it 2 cells)
    bit 8      Emoji_Presentation (FE0E makes it 1 cell)
    bits 9-10  Indic_Conjunct_Break: None Linker Consonant Extend
"""
import pathlib
import re
import sys

VERSION = '17.0.0'
GCB = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
INCB = ['None', 'Linker', 'Consonant', 'Extend']


def find(root, name):
    for sub in ('', 'ucd/', 'auxiliary/', 'emoji/', 'ucd/auxiliary/', 'ucd/emoji/'):
        p = root / (sub + name)
        if p.exists():
            return p.read_text(encoding='utf-8')
    raise SystemExit('missing ' + name)


def records(text):
    for line in text.splitlines():
        line = line.split('#')[0].strip()
        if line:
            yield [part.strip() for part in line.split(';')]


def span(s):
    a, _, b = s.partition('..')
    return int(a, 16), int(b or a, 16)


def generate(root):
    eaw_text = find(root, 'EastAsianWidth.txt')
    assert 'EastAsianWidth-%s' % VERSION in eaw_text
    gcb_text = find(root, 'GraphemeBreakProperty.txt')
    assert 'GraphemeBreakProperty-%s' % VERSION in gcb_text
    dcp_text = find(root, 'DerivedCoreProperties.txt')
    assert 'DerivedCoreProperties-%s' % VERSION in dcp_text
    emoji_text = find(root, 'emoji-data.txt')
    assert re.search(r'# Version: 17\.0', emoji_text)
    vs_text = find(root, 'emoji-variation-sequences.txt')
    assert re.search(r'# Version: 17\.0', vs_text)

    n = 0x110000
    wide = bytearray(n)
    listed = bytearray(n)
    for sp, val in records(eaw_text):
        a, b = span(sp)
        for c in range(a, b + 1):
            listed[c] = 1
            if val in ('W', 'F'):
                wide[c] = 1
    gcb = bytearray(n)
    for sp, val in records(gcb_text):
        a, b = span(sp)
        gcb[a:b + 1] = bytes([GCB.index(val)]) * (b - a + 1)
    incb = bytearray(n)
    for rec in records(dcp_text):
        if len(rec) == 3 and rec[1] == 'InCB':
            a, b = span(rec[0])
            incb[a:b + 1] = bytes([INCB.index(rec[2])]) * (b - a + 1)
    pict = bytearray(n)
    pres = bytearray(n)
    for sp, prop in records(emoji_text):
        a, b = span(sp)
        if prop == 'Extended_Pictographic':
            pict[a:b + 1] = b'\x01' * (b - a + 1)
        elif prop == 'Emoji_Presentation':
            pres[a:b + 1] = b'\x01' * (b - a + 1)
    vs16 = bytearray(n)
    for seq, style in ((r[0], r[1]) for r in records(vs_text)):
        cps = [int(x, 16) for x in seq.split()]
        if style == 'emoji style' and cps[1] == 0xFE0F:
            vs16[cps[0]] = 1

    words = []
    prev = None
    for c in range(n):
        w = 2 if wide[c] or pres[c] or (pict[c] and not listed[c]) else 1
        p = w | gcb[c] << 2 | pict[c] << 6 | vs16[c] << 7 | pres[c] << 8 | incb[c] << 9
        if p != prev:
            words.append(c << 11 | p)
            prev = p
    out = ['/* Generated by tools/gen_vt_width.py from Unicode %s (EastAsianWidth, GraphemeBreakProperty, DerivedCoreProperties' % VERSION,
           ' * InCB, emoji-data, emoji-variation-sequences). See THIRD_PARTY.md. Each word: (first code point << 11) | properties,',
           ' * the run lasting until the next word; the properties are described in tools/gen_vt_width.py and cui_vt_width.c. */',
           '#define CUI__VTW_N %d' % len(words),
           'static const uint32_t cui__vtw_table[CUI__VTW_N] = {']
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join('0x%08Xu' % v for v in words[i:i + 8]) + ',')
    out += ['};', '']
    out += compositions(root)
    return '\n'.join(out), dict(wide=wide, pres=pres, pict=pict, vs16=vs16, gcb=gcb)


def compositions(root):
    """Canonical compositions of two BMP code points (NFC's primary composites, Hangul left out): a character and a mark
    drawn as the one character fonts have (a + ring above = U+00E5)."""
    ud = find(root, 'UnicodeData.txt')
    dn = find(root, 'DerivedNormalizationProps.txt')
    assert 'DerivedNormalizationProps-%s' % VERSION in dn
    excl = set()
    for rec in records(dn):
        if len(rec) >= 2 and rec[1] == 'Full_Composition_Exclusion':
            a, b = span(rec[0])
            excl.update(range(a, b + 1))
    pairs = []
    for line in ud.splitlines():
        f = line.split(';')
        dec = f[5]
        if not dec or dec.startswith('<'):
            continue
        parts = [int(x, 16) for x in dec.split()]
        c = int(f[0], 16)
        if len(parts) != 2 or c in excl or max(parts + [c]) > 0xFFFF:
            continue
        pairs.append((parts[0], parts[1], c))
    pairs.sort()
    out = ['/* Canonical compositions of two BMP code points (UnicodeData.txt, without Full_Composition_Exclusion): first, second,',
           ' * the composite, sorted. */',
           '#define CUI__VTW_COMP_N %d' % len(pairs),
           'static const uint16_t cui__vtw_comp[CUI__VTW_COMP_N][3] = {']
    for i in range(0, len(pairs), 6):
        out.append('    ' + ', '.join('{0x%04X, 0x%04X, 0x%04X}' % p for p in pairs[i:i + 6]) + ',')
    out += ['};', '']
    return out


def c_utf8(cps):
    b = ''.join(chr(c) for c in cps).encode('utf-8')
    return '"' + ''.join('\\x%02X' % x for x in b) + '"'


def tests(root, props):
    gbt = find(root, 'GraphemeBreakTest.txt')
    assert 'GraphemeBreakTest-%s' % VERSION in gbt
    cases, skipped = [], 0
    for line in gbt.splitlines():
        line = line.split('#')[0].strip()
        if not line:
            continue
        toks = line.split()
        cps, words = [], []
        brk = None
        for t in toks:
            if t == '÷':
                brk = True
            elif t == '×':
                brk = False
            else:
                cps.append(int(t, 16))
                words.append(('%08X' % (int(t, 16) | (0x80000000 if brk else 0))))
        if any(0xD800 <= c <= 0xDFFF for c in cps):
            skipped += 1                     # a lone surrogate has no UTF-8 form
            continue
        cases.append(words)
    et = find(root, 'emoji-test.txt')
    assert re.search(r'# Version: 17\.0', et)
    full = []
    for line in et.splitlines():
        m = re.match(r'^([0-9A-F ]+?)\s*; fully-qualified', line)
        if m:
            full.append([int(x, 16) for x in m.group(1).split()])
    text_style = [c for c in range(0x110000) if props['vs16'][c]]
    wide = props['wide']
    ranges = []
    c = 0
    while c < 0x110000:
        if wide[c]:
            a = c
            while c + 1 < 0x110000 and wide[c + 1]:
                c += 1
            ranges.append((a, c))
        c += 1
    out = ['/* Generated by tools/gen_vt_width.py from Unicode %s: GraphemeBreakTest.txt (%d cases; %d with a lone surrogate' % (VERSION, len(cases), skipped),
           ' * left out), emoji-test.txt (the fully-qualified emoji), emoji-variation-sequences.txt and EastAsianWidth.txt. */',
           '/* grapheme break cases: code points, bit 31 set where a cluster starts; each case ends with 0xFFFFFFFF */',
           'static const uint32_t gbt_cases[] = {']
    for w in cases:
        out.append('    ' + ', '.join('0x%su' % x for x in w) + ', 0xFFFFFFFFu,')
    out += ['};', '#define GBT_COUNT %d' % len(cases), '',
            '/* every fully-qualified emoji: one cluster of 2 cells */',
            'static const char *const emoji_full[] = {']
    for i in range(0, len(full), 6):
        out.append('    ' + ', '.join(c_utf8(s) for s in full[i:i + 6]) + ',')
    out += ['};', '#define EMOJI_FULL_COUNT %d' % len(full), '',
            '/* the bases of the emoji style variation sequences: with FE0F 2 cells, with FE0E 1 */',
            'static const uint32_t vs_bases[] = {']
    for i in range(0, len(text_style), 10):
        out.append('    ' + ', '.join('0x%X' % c for c in text_style[i:i + 10]) + ',')
    out += ['};', '#define VS_BASES_COUNT %d' % len(text_style), '',
            '/* East Asian Width W and F, as ranges: 2 cells */',
            'static const uint32_t eaw_wide[][2] = {']
    for i in range(0, len(ranges), 6):
        out.append('    ' + ', '.join('{0x%X, 0x%X}' % r for r in ranges[i:i + 6]) + ',')
    out += ['};', '#define EAW_WIDE_COUNT %d' % len(ranges), '']
    return '\n'.join(out)


if __name__ == '__main__':
    root = pathlib.Path(sys.argv[1])
    here = pathlib.Path(__file__).resolve().parent.parent
    table, props = generate(root)
    (here / 'src/cui_vt_width.h').write_text(table, encoding='utf-8', newline='\n')
    (here / 'tests/test_vt_width_data.h').write_text(tests(root, props), encoding='utf-8', newline='\n')
    print('table words:', table.count('0x') - 0)
