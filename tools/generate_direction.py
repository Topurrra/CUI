"""Regenerate the compact Unicode first-strong table (Python Unicode 15.1.0)."""
import pathlib, unicodedata
assert unicodedata.unidata_version == '15.1.0'
data=[]
prev=None
for cp in range(0x110000):
    cls={'L':1,'R':2,'AL':2}.get(unicodedata.bidirectional(chr(cp)),0)
    if prev is not None and cls != prev:
        data.extend(((cp-1)|(prev<<21)).to_bytes(3,'little'))
    prev=cls
data.extend((0x10ffff|(prev<<21)).to_bytes(3,'little'))
out='/* Unicode '+unicodedata.unidata_version+' first-strong classes; generated by tools/generate_direction.py. */\n'
out+='static const unsigned char cui__strong_ranges[] = {\n'
out+='\n'.join('    '+','.join(str(x) for x in data[i:i+30])+',' for i in range(0,len(data),30))+'\n};\n'
(pathlib.Path(__file__).resolve().parents[1]/'src/cui_direction_data.h').write_text(out)
